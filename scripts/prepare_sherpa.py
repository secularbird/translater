"""Fetch and inspect a pinned official sherpa-onnx WASM distribution."""
from pathlib import Path
import hashlib
import tarfile
import urllib.request
import shutil
import json
import re

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / ".model-cache"
NAME = "sherpa-onnx-wasm-simd-1.12.15-vad-asr-zh_en_ja_ko_cantonese-sense_voice_small"
URL = f"https://github.com/k2-fsa/sherpa-onnx/releases/download/v1.12.15/{NAME}.tar.bz2"
SHA256 = "f7498b348a9c222634ad921a19dee99a147cc0a3350eaee10aadc6a3ea0553dd"


def main():
    CACHE.mkdir(exist_ok=True)
    archive = CACHE / f"{NAME}.tar.bz2"
    if not archive.exists():
        print("Downloading pinned sherpa-onnx runtime…", flush=True)
        urllib.request.urlretrieve(URL, archive)
    if hashlib.sha256(archive.read_bytes()).hexdigest() != SHA256:
        raise RuntimeError("sherpa-onnx archive checksum mismatch")
    with tarfile.open(archive) as package:
        package.extractall(CACHE, filter="data")
    source = CACHE / NAME
    target = ROOT / "public" / "wasm" / "sherpa"
    target.mkdir(parents=True, exist_ok=True)
    code = (source / "sherpa-onnx-wasm-main-vad-asr.js").read_text()
    # Remove only Emscripten's preloaded .data loader. We supply model files
    # through preRun instead, so the 240MB weights are not part of the app.
    marker = "var moduleOverrides="
    if marker not in code or 'Module["FS_createDataFile"]' not in code:
        raise RuntimeError("Unexpected pinned Emscripten layout")
    runtime = code[code.index(marker):]
    wrapper = """// sherpa-onnx v1.12.15, Apache-2.0. Generated by prepare_sherpa.py.
// Original .data preloader replaced by caller-provided preRun files.
export default function createSherpa(configuration) {
  return new Promise((resolve, reject) => {
    var Module = { ...configuration, noInitialRun: true,
      onRuntimeInitialized: () => resolve(Module),
      onAbort: reason => reject(new Error(String(reason))) };
"""
    (target / "runtime.mjs").write_text(wrapper + runtime + "\nModule.sonoraUnlink = path => FS.unlink(path);\n});\n}\n")
    api = (source / "sherpa-onnx-asr.js").read_text()
    (target / "recognizer.mjs").write_text("// sherpa-onnx v1.12.15, Apache-2.0.\n" + api + "\nexport { OfflineRecognizer };\n")
    vad_api = (source / 'sherpa-onnx-vad.js').read_text()
    # Upstream's classic script has two implicit globals; ES modules are strict.
    vad_api = vad_api.replace('  offset = 0;', '  let offset = 0;')
    (target / 'vad.mjs').write_text('// sherpa-onnx v1.12.15, Apache-2.0.\n' + vad_api + '\nexport { createVad };\n')
    metadata = json.loads(re.search(r'loadPackage\((\{.*?\})\)', code).group(1))
    entry = next(file for file in metadata['files'] if file['filename'] == '/silero_vad.onnx')
    with (source / 'sherpa-onnx-wasm-main-vad-asr.data').open('rb') as data:
        data.seek(entry['start'])
        (target / 'silero_vad.onnx').write_bytes(data.read(entry['end'] - entry['start']))
    shutil.copyfile(source / "sherpa-onnx-wasm-main-vad-asr.wasm", target / "sherpa.wasm")
    if not (target / 'LICENSE').exists():
        urllib.request.urlretrieve("https://raw.githubusercontent.com/k2-fsa/sherpa-onnx/v1.12.15/LICENSE", target / "LICENSE")
    ort = ROOT / "public" / "wasm" / "ort"
    ort.mkdir(parents=True, exist_ok=True)
    if not (ort / 'LICENSE').exists():
        urllib.request.urlretrieve("https://raw.githubusercontent.com/microsoft/onnxruntime/v1.22.0/LICENSE", ort / "LICENSE")
    print(f"Prepared pinned sherpa-onnx runtime in {target}")


if __name__ == "__main__":
    main()
